function rng(seed: number) {
  let s = seed
  return () => ((s = (s * 9301 + 49297) % 233280) / 233280)
}

export function makeRankItems(): RankItem[] {
  const r = rng(42)
  const pick = <T,>(a: T[]) => a[Math.floor(r() * a.length)]
  const mk = (gender: 'male' | 'female', titles: string[], cats: string[], tags: string[]) =>
    titles.map((title, i) => ({
      book_id_ext: `${gender === 'male' ? 7 : 6}${(3000000000 + i * 1373 + Math.floor(r() * 999)).toString()}`,
      title,
      author: pick(AUTHORS),
      category: cats[(i * 3 + Math.floor(r() * 3)) % cats.length],
      rank: i + 1,
      read_count: Math.round((1 - i / 34) * 4_800_000 * (0.6 + r() * 0.6)),
      word_count: Math.round(180_000 + r() * 2_200_000),
      abstract: `${title}——${gender === 'male' ? '一个普通人意外获得改变命运的机会，从底层一路逆袭，打脸、升级、收服强敌。' : '她被辜负过一次，这一次，她要亲手改写自己的命运，顺便收获一个把她宠上天的人。'}`,
      tags: Array.from(new Set([pick(tags), pick(tags), pick(tags)])),
      gender,
    }))
  return [...mk('male', MALE_TITLES, MALE_CATS, TAGS_M), ...mk('female', FEMALE_TITLES, FEMALE_CATS, TAGS_F)].map((x, i) => ({ ...x, id: i + 1 }))
}

