def _build() -> list[BannedPattern]:
    out: list[BannedPattern] = []
    for name, rx, cat, narr in _REGEXES:
        out.append(BannedPattern(name, re.compile(rx, re.M), cat, narr, 2 if cat == "句式" else 0))
    for cat, words in _LITERALS.items():
        for w in words:
            out.append(BannedPattern(w, re.compile(re.escape(w)), cat, cat in _NARRATION_ONLY_LITERAL_CATS, 1))
    return out


BANNED_PATTERNS: list[BannedPattern] = _build()

