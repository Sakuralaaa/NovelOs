# ---------- 量词搭配错误（小而准） ----------
@dataclass(frozen=True)
class MeasureRule:
    label: str
    regex: re.Pattern[str]
    hint: str


def _m(label: str, measure: str, nouns: str, hint: str) -> MeasureRule:
    # 数词 + 量词 + 至多 8 个修饰字（不跨标点） + 名词
    rx = re.compile(rf"[一两二三四五六七八九十几数半]{measure}[^，。！？；\n“”]{{0,8}}?(?:{nouns})")
    return MeasureRule(label, rx, hint)


